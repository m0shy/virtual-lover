# -*- coding: utf-8 -*-
"""QQ 小黄脸（face 段）——常用 id 表、发送白名单与 {{face:id}} 标记协议。

背景：此前框架收发两侧都"看不见"QQ 经典表情——收侧 face 段统一降级
``[表情]`` 丢 id，发侧根本没有 face 段构造器；人设承诺会撒娇卖萌，却
连一个 [飞吻] 都发不出来。本模块补齐两侧的"词汇表"：

- **收侧命名**（textutil 消费）：收到 ``{type: face, data: {id: 85}}``
  时降级为 ``[飞吻]`` 而不是 ``[表情]``，她才看得懂他发了什么表情；
- **发侧白名单**（发送层消费）：LLM 回复里写 ``{{face:85}}`` 标记，
  只放行 :data:`SEND_WHITELIST` 内的经典 id，防错码/防幻想 id；
- **标记协议**：``{{face:id}}`` 形式与 selfies 的 ``&&selfie_x&&``
  同族——LLM 只写标记，数组段由发送层构造，永不拼 CQ 码。

数据出处（clean-room，只读公开事实数据，未读任何上游实现源码）：
OneBot v11 规范 segment.md 的 face 段引用 richardchien/coolq-http-api
wiki 的「表情 CQ 码 ID 表」（191 个 id，id 17 空缺）；id→名称与
icqq/NapCat 生态通用 face 字典一致。本次实现将两份公开表联网交叉
核对后取常用子集：id 集合与名称逐条对得上，id 17 在两份来源中均
不存在。**表外 id 一律不编造**——未知 id 回落通用占位，绝不猜名称。

本模块只依赖标准库，不含任何账号/人设信息。
"""

from __future__ import annotations

import re

logger_name = "virtuallover.bridge.faces"

# ---------------------------------------------------------------------------
# 常用 face id → 名称表（收侧命名用；名称逐条来自公开表情表，未收的 id 不编造）
# ---------------------------------------------------------------------------

#: 40 个常用经典小黄脸（数字稳定，自 QQ 经典表情沿用至今）
FACE_NAMES: dict[int, str] = {
    0: "惊讶", 1: "撇嘴", 2: "色", 3: "发呆", 4: "得意", 5: "流泪",
    6: "害羞", 8: "睡", 9: "大哭", 10: "尴尬", 12: "调皮", 13: "呲牙",
    14: "微笑", 15: "难过", 18: "抓狂", 20: "偷笑", 21: "可爱", 22: "白眼",
    25: "困", 27: "流汗", 28: "憨笑", 29: "悠闲", 32: "疑问", 36: "衰",
    39: "再见", 49: "拥抱", 53: "蛋糕", 63: "玫瑰", 66: "爱心", 67: "心碎",
    69: "礼物", 75: "月亮", 76: "赞", 85: "飞吻", 104: "哈欠",
    106: "委屈", 109: "亲亲", 122: "爱你", 129: "挥手", 182: "笑哭",
}

# ---------------------------------------------------------------------------
# 发送白名单（防错码：LLM 只允许写白名单内的 id）
# ---------------------------------------------------------------------------

#: 20 个经典必中小黄脸（FACE_NAMES 的子集；撒娇/卖萌/道歉/晚安够用了）。
#: 白名单外 id 的 {{face:id}} 标记会被 extract_face_markers 直接丢弃。
SEND_WHITELIST: frozenset[int] = frozenset(
    {
        1,    # 撇嘴
        5,    # 流泪
        6,    # 害羞
        8,    # 睡
        9,    # 大哭
        12,   # 调皮
        13,   # 呲牙
        14,   # 微笑
        15,   # 难过
        18,   # 抓狂
        20,   # 偷笑
        21,   # 可爱
        25,   # 困
        28,   # 憨笑
        32,   # 疑问
        49,   # 拥抱
        85,   # 飞吻
        106,  # 委屈
        109,  # 亲亲
        122,  # 爱你
    }
)

# ---------------------------------------------------------------------------
# {{face:id}} 标记协议（与 selfies 的 &&selfie_x&& 同族的 LLM 输出标记）
# ---------------------------------------------------------------------------

# 完整标记：{{face:数字}}（花括号内不容空白，LLM 速查文案即此形态）
FACE_MARKER_RE = re.compile(r"\{\{face:(\d+)\}\}")

# 残缺清洗：未闭合的 {{face:14、孤立的 {{、}} 等残迹——只清花括号残迹本身，
# 标记内的词（face:14 的 "face:14"）与 memes 同口径按正文保留（保守清洗）。
LEFTOVER_BRACE_RE = re.compile(r"\{\{+|\}\}+")


def extract_face_markers(text: str) -> tuple[str, list[int]]:
    """剥出 LLM 回复里的 ``{{face:id}}`` 标记。

    返回 ``(清洗后文本, 待发 face id 列表)``：

    - 白名单内 id：按出现顺序进入返回列表（同一 id 可重复出现）；
    - 白名单外 id（错码/幻想 id）：只丢弃标记，不进列表、不报错；
    - 标记清除后收敛多余空白；残缺花括号（``{{face:14``、孤立 ``{{``）
      只清 ``{{``/``}}`` 残迹本身，其余按正文保留（保守清洗）。
    """
    ids = [
        int(m.group(1)) for m in FACE_MARKER_RE.finditer(text or "")
        if int(m.group(1)) in SEND_WHITELIST
    ]
    cleaned = FACE_MARKER_RE.sub("", text or "")
    cleaned = LEFTOVER_BRACE_RE.sub("", cleaned)
    cleaned = re.sub(r"[ \t]+\n", "\n", cleaned)
    cleaned = re.sub(r"[ \t]{2,}", " ", cleaned)
    cleaned = re.sub(r"\n{3,}", "\n\n", cleaned)
    return cleaned.strip(), ids


def faces_cheatsheet() -> str:
    """给 LLM 的速查文案（一行）：``{{face:14}}=微笑 {{face:85}}=飞吻 …``。

    只列发送白名单内的 id——列出她发不出的 id 只会诱导幻觉输出。
    """
    entries = [
        f"{{{{face:{face_id}}}}}={FACE_NAMES[face_id]}"
        for face_id in sorted(SEND_WHITELIST)
        if face_id in FACE_NAMES
    ]
    return " ".join(entries)
